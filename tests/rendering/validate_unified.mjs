import fs from 'node:fs';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<!doctype html><html><body></body></html>');
globalThis.window=dom.window; globalThis.document=dom.window.document;
globalThis.Element=dom.window.Element;
const {default:mermaid}=await import('mermaid');
mermaid.initialize({startOnLoad:false,securityLevel:'strict'});
const [mmd,json]=process.argv.slice(2);
const text=fs.readFileSync(mmd,'utf8'), report=JSON.parse(fs.readFileSync(json,'utf8'));
await mermaid.parse(text);
const diagram=await mermaid.mermaidAPI.getDiagramFromText(text);
const vertices=diagram.db.getVertices(),edges=diagram.db.getEdges();
const id=x=>'n'+crypto.createHash('sha256').update(JSON.stringify(x)).digest('hex').slice(0,20);
const expected=report.cfg.edges.map(e=>id(e.source)+'>'+id(e.target)).sort();
if(JSON.stringify(expected)!==JSON.stringify(edges.map(e=>e.start+'>'+e.end).sort())) throw Error('CFG endpoints changed');
if(JSON.stringify([...vertices.keys()])!==JSON.stringify(report.ordering.display_order.map(id))) throw Error('Display order/identity changed');
const records=prefix=>text.split('\n').filter(l=>l.startsWith('  %% '+prefix+' ')).map(l=>JSON.parse(l.slice(prefix.length+6)));
assert.deepEqual(records('flow-node'),report.cfg.blocks);
assert.deepEqual(records('flow-edge'),report.cfg.edges);
const {cfg,...metadata}=report;
assert.deepEqual(records('flow-meta')[0],metadata);
console.log(JSON.stringify({status:'PASS',vertices:vertices.size,edges:edges.length}));

def _write_if_missing(path: Path, text: str, force: bool = False) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not force:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def init(root: Path, force: bool = False) -> int:
    written = []
    for path, text in (
        (root / HOOK_CONFIG, json.dumps(HOOK_CONTENT, indent=2) + "\n"),
        (root / AGENT_FILE, AGENT_CONTENT),
        (root / ARCHITECT_AGENT_FILE, ARCHITECT_AGENT_CONTENT),
        (root / EXTRACT_AGENT_FILE, EXTRACT_AGENT_CONTENT),
        (root / COPILOT_INSTRUCTIONS, INSTRUCTIONS_CONTENT),
        (root / NOTES_FILE, NOTES_CONTENT),
    ):
        if _write_if_missing(path, text, force=force):
            written.append(path.relative_to(root).as_posix())

    ignore_entries = [
        ".kgmaker/graph.json", ".kgmaker/semantic-input.json",
        ".kgmaker/semantic-update.json", ".kgmaker/semantic-update.md",
        ".kgmaker/semantic-patch.json", ".kgmaker/confluence-index.json",
    ]
    gitignore_path = root / GITIGNORE
    if not gitignore_path.exists():
        gitignore_path.write_text("\n".join(ignore_entries) + "\n", encoding="utf-8")
        written.append(".gitignore")
    else:
        existing = gitignore_path.read_text(encoding="utf-8")
        missing = [entry for entry in ignore_entries if entry not in existing.splitlines()]
        if missing:
            gitignore_path.write_text(existing.rstrip() + "\n\n# Local kgmaker index\n" + "\n".join(missing) + "\n", encoding="utf-8")
            written.append(".gitignore")

    print("Initialized kgmaker in this repository.")
    print("Created: " + (", ".join(written) if written else "nothing; existing files were preserved"))
    print("Next: kgmaker scan")
    return 0


def scan(root: Path, generate_docs: bool = True, confluence_dir: str | None = None, report: str | None = None) -> int:
    graph, semantic_counts, semantic_error = apply_semantic_layer(scan_repository(root), root)
    export_root = resolve_confluence_dir(root, confluence_dir)
    if export_root is not None:
        documents, attachments, _ = ingest_export(export_root, root)
        assertions = validate_documents(documents, graph)
        persist_validation_index(root, assertions)
        graph = merge_into_graph(graph, documents, attachments, assertions)
        report_path = Path(report or DEFAULT_REPORT_FILE)
        if not report_path.is_absolute():
            report_path = root / report_path
        render_report(assertions, report_path, export_root)
        report_label = report_path.relative_to(root) if report_path.is_relative_to(root) else report_path
        print(f"Confluence: {len(documents)} pages, {len(attachments)} attachments, report {report_label}")
    graph_path, markdown_path = save_graph(graph, root, generate_docs=generate_docs)
    file_count = sum(node.kind == "file" for node in graph.nodes)
    symbol_count = len(graph.nodes) - file_count
    print(f"Indexed {file_count} files, {symbol_count} declarations/sections, and {len(graph.edges)} relationships.")
    print(f"Machine index: {graph_path.relative_to(root)}")
    if generate_docs:
        print(f"Human view: {markdown_path.relative_to(root)}")
        print(f"Diagram: {(root / MERMAID_FILE).relative_to(root)}")
    else:
        print("Documentation and diagram generation skipped (--no-docs).")
    if semantic_counts != (0, 0):
        print(f"Semantic layer: {semantic_counts[0]} concepts, {semantic_counts[1]} relationships.")
    if semantic_error:
        print(f"Some semantic entries were omitted: {semantic_error}", file=sys.stderr)
    return 0


def status(root: Path) -> int:
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan`.")
        return 1
    live, _, semantic_error = apply_semantic_layer(scan_repository(root), root)
    indexed = graph.files
    changed = sorted(path for path, digest in live.files.items() if indexed.get(path) != digest)
    removed = sorted(set(indexed) - set(live.files))
    graph_changed = graph.nodes != live.nodes or graph.edges != live.edges
    if not changed and not removed and not graph_changed and not semantic_error:
        print(f"Graph is current: {len(indexed)} files, {len(graph.nodes)} nodes, {len(graph.edges)} relationships.")
        return 0
    print(f"Graph is stale: {len(changed)} changed/new, {len(removed)} removed files, semantic/graph differences: {graph_changed}. Run `kgmaker scan`.")
    if semantic_error:
        print(f"  semantic layer: {semantic_error}")
    for path in changed[:10]:
        print(f"  changed: {path}")
    for path in removed[:10]:
        print(f"  removed: {path}")
    return 2


def check(root: Path) -> int:
    """CI-friendly validation of the committed Markdown and Mermaid graph views."""
    graph, _, semantic_error = apply_semantic_layer(scan_repository(root), root)
    if semantic_error:
        print(f"Semantic artifact is stale or invalid: {semantic_error}")
        return 2
    markdown_path = root / MARKDOWN_FILE
    expected = render_markdown(graph)
    mermaid_path = root / MERMAID_FILE
    expected_mermaid = render_mermaid(graph)
    try:
        current = markdown_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        current = ""
    if current != expected:
        print("Graph documentation is missing or stale. Run `kgmaker scan` and commit `.kgmaker/GRAPH.md`.")
        return 2
    try:
        current_mermaid = mermaid_path.read_text(encoding="utf-8")
    except (OSError, UnicodeError):
        current_mermaid = ""
    if current_mermaid != expected_mermaid:
        print("Graph visualization is missing or stale. Run `kgmaker scan` and commit `.kgmaker/GRAPH.mmd`.")
        return 2
    file_count = sum(node.kind == "file" for node in graph.nodes)
    print(f"Graph documentation is current: {file_count} files, {len(graph.nodes)} nodes, {len(graph.edges)} relationships.")
    return 0


def docs(root: Path, action: str | None = None, confluence_dir: str | None = None, report: str | None = None) -> int:
    """Regenerate graph views or check local Confluence documentation."""
    if action in {"check", "report"}:
        graph = load_graph(root) or scan_repository(root)
        pages, contradictions, review, report_path = documentation_check(root, confluence_dir, report, graph)
        print(f"Analyzed: {pages} HTML pages")
        print(f"Contradictions: {contradictions}")
        print(f"Needs review: {review}")
        print(f"Report: {report_path.relative_to(root) if report_path.is_relative_to(root) else report_path}")
        return 0
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1
    markdown_path = root / MARKDOWN_FILE
    markdown_path.parent.mkdir(parents=True, exist_ok=True)
    markdown_path.write_text(render_markdown(graph), encoding="utf-8")
    mermaid_path = root / MERMAID_FILE
    mermaid_path.write_text(render_mermaid(graph), encoding="utf-8")
    print(f"Generated: {markdown_path.relative_to(root)}")
    print(f"Generated: {mermaid_path.relative_to(root)}")
    return 0



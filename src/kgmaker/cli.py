def semantic_update(root: Path, base_ref: str, note_path: str | None = None, token_budget: int | None = None) -> int:
    """Prepare a token-bounded semantic update package from Git changes."""
    previous_graph = load_graph(root)
    graph = scan_repository(root)
    try:
        update = build_semantic_update(graph, root, base_ref, note_path, previous_graph, token_budget=token_budget)
    except SemanticValidationError as error:
        print(f"Could not prepare semantic update: {error}", file=sys.stderr)
        return 2
    if not update["changed_files"]:
        patch_path = root / SEMANTIC_PATCH_FILE
        if patch_path.exists():
            patch_path.unlink(missing_ok=True)
            print("Discarded an orphaned semantic patch because this packet has no changes.")
        print(f"No changes found relative to {base_ref}; semantic update not needed.")
        return 0
    output_json = root / SEMANTIC_UPDATE_FILE
    output_md = root / SEMANTIC_UPDATE_MARKDOWN
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(update, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    patch_path = root / SEMANTIC_PATCH_FILE
    if patch_path.exists():
        try:
            existing_patch = json.loads(patch_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            existing_patch = None
        if not isinstance(existing_patch, dict) or existing_patch.get("update_id") != update["update_id"]:
            # A patch is strictly scoped to one packet. Leaving an old patch in
            # place makes repeated `semantic update`/`semantic apply` attempts
            # fail forever, so discard only this generated, stale artifact.
            patch_path.unlink(missing_ok=True)
            print("Discarded a stale semantic patch; the agent must create a new patch for this packet.")
    changed = [item for item in update["changed_files"] if not item.get("sensitive")]
    paths = "\n".join(f"- `{item['status']} {item['path']}`" for item in update["changed_files"])
    changed_paths = {item["path"] for item in update["changed_files"]}
    declaration_lines = []
    for item in update["context_nodes"]:
        if item["path"] not in changed_paths:
            continue
        state = "present" if item["present_now"] else "removed"
        location = f":{item['line']}" if item.get("line") else ""
        signature = f" — `{item['signature']}`" if item.get("signature") else ""
        declaration_lines.append(f"- `{state}` {item['kind']} **{item['name']}** in `{item['path']}{location}`{signature}")
    declaration_summary = "\n".join(declaration_lines) or "- No declarations or sections were extracted from the changed files."
    truncated_diffs = sum(bool(item.get("diff_truncated")) for item in update["changed_files"])
    legacy = "\n\nThe existing artifact uses the legacy global fingerprint. Review all listed semantic entries; the patch will migrate the artifact to per-file snapshots.\n" if update["legacy_artifact"] else ""
    note = "\nA change note is included in the JSON packet.\n" if update.get("change_note") else ""
    markdown = f"""# kgmaker semantic update

Update ID: `{update['update_id']}`  
Base: `{update['base_ref']}` (`{update['base_commit'][:12]}`)  
Changed files: {len(update['changed_files'])}  
Affected graph nodes: {len(update['context_nodes'])}  
Existing semantic entries to review: {len(update['affected_semantic_nodes'])} concepts and {len(update['affected_semantic_edges'])} relationships  
Diffs truncated by context budget: {truncated_diffs}  
Requested token budget (approx.): {update['token_budget']}  
Estimated diff tokens: {update['estimated_diff_tokens']}  
Nearby graph context truncated: {update['context_nodes_truncated'] or update['context_edges_truncated']}
{note}{legacy}
## Changed paths

{paths}

## Changed declarations and sections

{declaration_summary}

## Next steps

Use the `kgmaker-extract` agent with this file and `.kgmaker/semantic-update.json`. Have it write `.kgmaker/semantic-patch.json`, then run `kgmaker semantic apply`, `kgmaker semantic validate`, and `kgmaker scan`. Unrelated semantic entries should be preserved.

Diffs and the change packet stay local; do not commit them unless you explicitly want to share those changes.
"""
    output_md.write_text(markdown, encoding="utf-8")
    print(f"Prepared {len(update['changed_files'])} changed paths and {len(update['context_nodes'])} nearby graph nodes.")
    print(f"Review: {output_md.relative_to(root)}")
    print(f"Agent input: {output_json.relative_to(root)}")
    print(f"Agent output: {(root / SEMANTIC_PATCH_FILE).relative_to(root)}")
    return 0


def semantic_apply(root: Path) -> int:
    """Apply a validated-in-scope Copilot semantic patch to the stored artifact."""
    try:
        update = json.loads((root / SEMANTIC_UPDATE_FILE).read_text(encoding="utf-8"))
        patch = json.loads((root / SEMANTIC_PATCH_FILE).read_text(encoding="utf-8"))
        graph = scan_repository(root)
        candidate = apply_semantic_patch(patch, update, graph, root)
    except (OSError, UnicodeError, json.JSONDecodeError, SemanticValidationError) as error:
        print(f"Semantic patch was not applied: {error}", file=sys.stderr)
        return 2
    artifact_path = root / SEMANTIC_FILE
    artifact_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = artifact_path.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(candidate, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(artifact_path)
    print(f"Applied semantic patch: {len(candidate['nodes'])} concepts, {len(candidate['edges'])} relationships total.")
    print("Next: kgmaker semantic validate && kgmaker scan")
    return 0



INSTRUCTIONS_CONTENT = """# kgmaker repository context

This repository uses kgmaker with GitHub Copilot CLI. `.kgmaker/GRAPH.md` is a local structural map of the repository; `.kgmaker/NOTES.md` contains verified semantic notes. Use both to navigate, then verify every conclusion in source. Run `kgmaker scan` after structural changes. Do not treat heuristic call edges as confirmed behavior. The graph is generated locally and must not contain secrets, credentials, or external links.
"""

NOTES_CONTENT = """# Repository knowledge notes

This file is for verified concepts and relationships that are not clear from static structure alone. Keep notes concise and grounded in source files. Do not add external URLs or secrets.
"""

HOOK_CONTENT = {
    "version": 1,
    "hooks": {
        "sessionStart": [
            {
                "type": "command",
                "bash": "python -m kgmaker.cli hook-context",
                "powershell": "python -m kgmaker.cli hook-context",
                "cwd": ".",
                "timeoutSec": 30,
            }
        ]
    },
}


def _write_if_missing(path: Path, text: str, force: bool = False) -> bool:
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not force:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def init(root: Path, force: bool = False) -> int:
    written = []
    for path, text in (
        (root / HOOK_CONFIG, json.dumps(HOOK_CONTENT, indent=2) + "\n"),
        (root / AGENT_FILE, AGENT_CONTENT),
        (root / COPILOT_INSTRUCTIONS, INSTRUCTIONS_CONTENT),
        (root / NOTES_FILE, NOTES_CONTENT),
    ):
        if _write_if_missing(path, text, force=force):
            written.append(path.relative_to(root).as_posix())

    ignore_entry = ".kgmaker/graph.json\n"
    gitignore_path = root / GITIGNORE
    if not gitignore_path.exists():
        gitignore_path.write_text(ignore_entry, encoding="utf-8")
        written.append(".gitignore")
    else:
        existing = gitignore_path.read_text(encoding="utf-8")
        if ".kgmaker/graph.json" not in existing:
            gitignore_path.write_text(existing.rstrip() + "\n\n# Local kgmaker index\n" + ignore_entry, encoding="utf-8")
            written.append(".gitignore")

    print("Initialized kgmaker in this repository.")
    print("Created: " + (", ".join(written) if written else "nothing; existing files were preserved"))
    print("Next: kgmaker scan")
    return 0


def scan(root: Path) -> int:
    graph = scan_repository(root)
    graph_path, markdown_path = save_graph(graph, root)
    file_count = sum(node.kind == "file" for node in graph.nodes)
    symbol_count = len(graph.nodes) - file_count
    print(f"Indexed {file_count} files, {symbol_count} declarations/sections, and {len(graph.edges)} relationships.")
    print(f"Machine index: {graph_path.relative_to(root)}")
    print(f"Human view: {markdown_path.relative_to(root)}")
    return 0


def status(root: Path) -> int:
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan`.")
        return 1
    live = scan_repository(root)
    indexed = graph.files
    changed = sorted(path for path, digest in live.files.items() if indexed.get(path) != digest)
    removed = sorted(set(indexed) - set(live.files))
    if not changed and not removed:
        print(f"Graph is current: {len(indexed)} files, {len(graph.nodes)} nodes, {len(graph.edges)} relationships.")
        return 0
    print(f"Graph is stale: {len(changed)} changed/new and {len(removed)} removed files. Run `kgmaker scan`.")
    for path in changed[:10]:
        print(f"  changed: {path}")
    for path in removed[:10]:
        print(f"  removed: {path}")
    return 2


def query(root: Path, terms: str, limit: int = 10) -> int:
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1
    query_terms = [part.lower() for part in terms.split() if part]
    nodes = {node.id: node for node in graph.nodes}
    scores: dict[str, int] = {}
    for node in graph.nodes:
        haystack = f"{node.name} {node.path} {node.signature or ''} {node.summary or ''}".lower()
        score = sum(4 if term == node.name.lower() else 2 if term in node.name.lower() else 1 if term in haystack else 0 for term in query_terms)
        if score:
            scores[node.id] = score
    if not scores:
        print(f"No graph entries matched: {terms}")
        return 0
    for edge in graph.edges:
        if edge.source in scores:
            scores[edge.target] = max(scores.get(edge.target, 0), scores[edge.source] - 1)
    ranked = sorted(scores.items(), key=lambda item: (-item[1], nodes[item[0]].path, nodes[item[0]].line or 0))
    print(f"Matches for {terms!r}:")
    for node_id, score in ranked[:limit]:
        node = nodes[node_id]
        location = f":{node.line}" if node.line else ""
        signature = f" — {node.signature}" if node.signature else ""
        print(f"- [{node.kind}] {node.path}{location}: {node.name}{signature} (score {score})")
    return 0


def hook_context(root: Path) -> int:
    """Refresh the graph and emit sessionStart additionalContext as JSON."""
    try:
        graph = scan_repository(root)
        save_graph(graph, root)
        context = render_context(graph, root=root)
        sys.stdout.write(json.dumps({"additionalContext": context}, ensure_ascii=False) + "\n")
        return 0
    except Exception as error:  # hooks must not break a Copilot session
        print(f"kgmaker hook skipped: {error}", file=sys.stderr)
        sys.stdout.write("{}\n")
        return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="kgmaker", description="Local repository knowledge graph for GitHub Copilot CLI")
    parser.add_argument("--version", action="version", version=f"kgmaker {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    init_parser = sub.add_parser("init", help="add Copilot hooks, instructions and the kgmaker agent")
    init_parser.add_argument("--root", type=Path, default=Path.cwd())
    init_parser.add_argument("--force", action="store_true", help="overwrite kgmaker-managed Copilot files")

    scan_parser = sub.add_parser("scan", help="scan source files and update the local graph")
    scan_parser.add_argument("--root", type=Path, default=Path.cwd())

    status_parser = sub.add_parser("status", help="check whether the stored graph matches current source")
    status_parser.add_argument("--root", type=Path, default=Path.cwd())

    query_parser = sub.add_parser("query", help="find likely files and declarations")
    query_parser.add_argument("terms", nargs="+", help="words to search in graph names, paths and summaries")
    query_parser.add_argument("--root", type=Path, default=Path.cwd())
    query_parser.add_argument("--limit", type=int, default=10)

    hook_parser = sub.add_parser("hook-context", help=argparse.SUPPRESS)
    hook_parser.add_argument("--root", type=Path, default=Path.cwd())
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    root = args.root.resolve()
    if args.command == "init":
        code = init(root, args.force)
    elif args.command == "scan":
        code = scan(root)
    elif args.command == "status":
        code = status(root)
    elif args.command == "query":
        code = query(root, " ".join(args.terms), args.limit)
    elif args.command == "hook-context":
        code = hook_context(root)
    else:
        parser.error("unknown command")
        return
    raise SystemExit(code)


if __name__ == "__main__":
    main()

def impact(root: Path, changed_files: list[str]) -> int:
    """Show files that depend on changed files via imports and call candidates."""
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1

    root = root.resolve()
    file_nodes = {node.id: node.path for node in graph.nodes if node.kind == "file"}
    node_by_id = {node.id: node for node in graph.nodes}
    path_nodes = set(file_nodes.values())
    seeds: set[str] = set()
    for raw_path in changed_files:
        candidate = Path(raw_path)
        try:
            resolved = (candidate if candidate.is_absolute() else root / candidate).resolve()
            relative = resolved.relative_to(root).as_posix()
        except (OSError, ValueError):
            print(f"Path is outside the repository: {raw_path}", file=sys.stderr)
            return 2
        if relative not in path_nodes:
            print(f"File is not in the graph: {raw_path}", file=sys.stderr)
            return 2
        seeds.add(relative)

    # Edges point from a consumer to its dependency. Reverse them to find consumers.
    dependents: dict[str, set[tuple[str, str]]] = {}
    for edge in graph.edges:
        if edge.kind == "imports":
            source_path = file_nodes.get(edge.source)
            target_path = file_nodes.get(edge.target)
            relation = "import"
        elif edge.kind == "calls":
            source_path = file_nodes.get(edge.source)
            target = node_by_id.get(edge.target)
            target_path = target.path if target else None
            relation = "candidate call"
        else:
            continue
        if source_path and target_path and source_path != target_path:
            dependents.setdefault(target_path, set()).add((source_path, relation))

    distance: dict[str, int] = {path: 0 for path in seeds}
    relations: dict[str, set[str]] = {}
    queue = sorted(seeds)
    cursor = 0
    while cursor < len(queue):
        dependency = queue[cursor]
        cursor += 1
        next_distance = distance[dependency] + 1
        for dependent, relation in sorted(dependents.get(dependency, set())):
            if dependent in seeds:
                continue
            relations.setdefault(dependent, set()).add(relation)
            if dependent not in distance:
                distance[dependent] = next_distance
                queue.append(dependent)

    print("Potential impact for: " + ", ".join(sorted(seeds)))
    impacted = sorted((path for path in distance if path not in seeds), key=lambda path: (distance[path], path))
    if not impacted:
        print("No dependent files found in the current graph.")
        return 0
    for path in impacted:
        kinds = ", ".join(sorted(relations.get(path, set())))
        confidence = "exact" if kinds == "import" else "candidate" if kinds == "candidate call" else "mixed"
        hops = distance[path]
        print(f"- {path} ({hops} hop{'s' if hops != 1 else ''}; {confidence}: {kinds})")
    print("Import links are source-resolved; call links are name-based candidates. Review source before acting.")
    return 0


def query(root: Path, terms: str, limit: int = 10, scope: str = "production",
          context_id: str | None = None) -> int:
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1
    try:
        from .feature import current_graph
        graph, _, _ = current_graph(root)
        from .views import select_context
        context_id = select_context(graph, scope, context_id)
    except ValueError as error:
        print(str(error), file=sys.stderr)
        return 2
    matches = query_nodes(graph, terms, limit, scope, context_id)
    if not matches:
        print(f"No graph entries matched: {terms}")
        return 0
    print(f"Matches for {terms!r}:")
    for node, score in matches:
        location = f":{node.line}" if node.line else ""
        signature = f" — {node.signature}" if node.signature else ""
        print(f"- [{node.kind}] {node.path}{location}: {node.name}{signature} (score {score})")
    return 0


def memory_capture(root: Path, base: str, validation_values: list[str]) -> int:
    """Capture one idempotent Git-backed implementation episode."""
    try:
        previous_graph = load_graph(root)
        if previous_graph is None:
            raise CaptureError("no readable pre-task graph found; run `kgmaker scan` before implementation")
        validations = parse_validations(validation_values)
        structural = scan_repository(root)
        semantic_path = root / SEMANTIC_FILE
        if semantic_path.exists():
            data = json.loads(semantic_path.read_text(encoding="utf-8"))
            validate_semantic_data(data, structural, root)
        else:
            data = {
                "schema_version": 3,
                "files": dict(structural.files),
                "nodes": [],
                "edges": [],
                "episodes": [],
            }
        if not isinstance(data, dict) or data.get("schema_version") not in {1, 2, 3}:
            raise CaptureError("semantic artifact must use schema_version 1, 2, or 3")
        current_graph, _, semantic_error = apply_semantic_layer(structural, root)
        if semantic_error:
            raise CaptureError(f"semantic artifact must be refreshed before capture: {semantic_error}")
        episode = build_capture_episode(root, base, previous_graph, current_graph, validations)
        existing = data.get("episodes", []) if data.get("schema_version") == 3 else []
        if not isinstance(existing, list):
            raise CaptureError("semantic artifact episodes must be an array")
        duplicate = next(
            (item for item in existing if isinstance(item, dict)
             and item.get("worktree_fingerprint") == episode["worktree_fingerprint"]),
            None,
        )
        if duplicate is not None:
            print(f"Implementation episode already recorded: {duplicate.get('id', 'unknown')}")
            return 0
        candidate = {
            "schema_version": 3,
            "files": dict(structural.files),
            "nodes": list(data.get("nodes", [])),
            "edges": list(data.get("edges", [])),
            "episodes": [*existing, episode],
        }
        validate_semantic_data(candidate, structural, root)
        semantic_path.parent.mkdir(parents=True, exist_ok=True)
        temporary = semantic_path.with_suffix(".json.tmp")
        temporary.write_text(json.dumps(candidate, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        temporary.replace(semantic_path)
    except (OSError, UnicodeError, json.JSONDecodeError, CaptureError, SemanticValidationError, ValueError) as error:
        print(f"Implementation memory was not captured: {error}", file=sys.stderr)
        return 2
    print(f"Captured implementation episode: {episode['id']}")
    print("Next: kgmaker scan")
    return 0



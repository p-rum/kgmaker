def semantic_update(root: Path, base_ref: str, note_path: str | None = None, token_budget: int | None = None) -> int:
    """Prepare a token-bounded semantic update package from Git changes."""
    previous_graph = load_graph(root)
    graph = scan_repository(root)
    try:
        update = build_semantic_update(graph, root, base_ref, note_path, previous_graph, token_budget=token_budget)
    except SemanticValidationError as error:
        print(f"Could not prepare semantic update: {error}", file=sys.stderr)
        return 2
    if not update["changed_files"]:
        print(f"No changes found relative to {base_ref}; semantic update not needed.")
        return 0
    output_json = root / SEMANTIC_UPDATE_FILE
    output_md = root / SEMANTIC_UPDATE_MARKDOWN
    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(update, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    patch_path = root / SEMANTIC_PATCH_FILE
    if patch_path.exists():
        try:
            existing_patch = json.loads(patch_path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            existing_patch = None
        if not isinstance(existing_patch, dict) or existing_patch.get("update_id") != update["update_id"]:
            # A patch is strictly scoped to one packet. Leaving an old patch in
            # place makes repeated `semantic update`/`semantic apply` attempts
            # fail forever, so discard only this generated, stale artifact.
            patch_path.unlink(missing_ok=True)
            print("Discarded a stale semantic patch; the agent must create a new patch for this packet.")
    changed = [item for item in update["changed_files"] if not item.get("sensitive")]
    paths = "\n".join(f"- `{item['status']} {item['path']}`" for item in update["changed_files"])
    changed_paths = {item["path"] for item in update["changed_files"]}
    declaration_lines = []
    for item in update["context_nodes"]:
        if item["path"] not in changed_paths:
            continue
        state = "present" if item["present_now"] else "removed"
        location = f":{item['line']}" if item.get("line") else ""
        signature = f" — `{item['signature']}`" if item.get("signature") else ""
        declaration_lines.append(f"- `{state}` {item['kind']} **{item['name']}** in `{item['path']}{location}`{signature}")
    declaration_summary = "\n".join(declaration_lines) or "- No declarations or sections were extracted from the changed files."
    truncated_diffs = sum(bool(item.get("diff_truncated")) for item in update["changed_files"])
    legacy = "\n\nThe existing artifact uses the legacy global fingerprint. Review all listed semantic entries; the patch will migrate the artifact to per-file snapshots.\n" if update["legacy_artifact"] else ""
    note = "\nA change note is included in the JSON packet.\n" if update.get("change_note") else ""
    markdown = f"""# kgmaker semantic update

Update ID: `{update['update_id']}`  
Base: `{update['base_ref']}` (`{update['base_commit'][:12]}`)  
Changed files: {len(update['changed_files'])}  
Affected graph nodes: {len(update['context_nodes'])}  
Existing semantic entries to review: {len(update['affected_semantic_nodes'])} concepts and {len(update['affected_semantic_edges'])} relationships  
Diffs truncated by context budget: {truncated_diffs}  
Requested token budget (approx.): {update['token_budget']}  
Estimated diff tokens: {update['estimated_diff_tokens']}  
Nearby graph context truncated: {update['context_nodes_truncated'] or update['context_edges_truncated']}
{note}{legacy}
## Changed paths

{paths}

## Changed declarations and sections

{declaration_summary}

## Next steps

Use the `kgmaker-extract` agent with this file and `.kgmaker/semantic-update.json`. Have it write `.kgmaker/semantic-patch.json`, then run `kgmaker semantic apply`, `kgmaker semantic validate`, and `kgmaker scan`. Unrelated semantic entries should be preserved.

Diffs and the change packet stay local; do not commit them unless you explicitly want to share those changes.
"""
    output_md.write_text(markdown, encoding="utf-8")
    print(f"Prepared {len(update['changed_files'])} changed paths and {len(update['context_nodes'])} nearby graph nodes.")
    print(f"Review: {output_md.relative_to(root)}")
    print(f"Agent input: {output_json.relative_to(root)}")
    print(f"Agent output: {(root / SEMANTIC_PATCH_FILE).relative_to(root)}")
    return 0


def semantic_apply(root: Path) -> int:
    """Apply a validated-in-scope Copilot semantic patch to the stored artifact."""
    try:
        update = json.loads((root / SEMANTIC_UPDATE_FILE).read_text(encoding="utf-8"))
        patch = json.loads((root / SEMANTIC_PATCH_FILE).read_text(encoding="utf-8"))
        graph = scan_repository(root)
        candidate = apply_semantic_patch(patch, update, graph, root)
    except (OSError, UnicodeError, json.JSONDecodeError, SemanticValidationError) as error:
        print(f"Semantic patch was not applied: {error}", file=sys.stderr)
        return 2
    artifact_path = root / SEMANTIC_FILE
    artifact_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = artifact_path.with_suffix(".json.tmp")
    temporary.write_text(json.dumps(candidate, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    temporary.replace(artifact_path)
    print(f"Applied semantic patch: {len(candidate['nodes'])} concepts, {len(candidate['edges'])} relationships total.")
    print("Next: kgmaker semantic validate && kgmaker scan")
    return 0


def semantic_validate(root: Path) -> int:
    """Validate an agent-written artifact against a fresh structural scan."""
    artifact = root / SEMANTIC_FILE
    try:
        data = json.loads(artifact.read_text(encoding="utf-8"))
        graph = scan_repository(root)
        nodes, edges = validate_semantic_data(data, graph, root)
    except (OSError, UnicodeError, json.JSONDecodeError, SemanticValidationError) as error:
        print(f"Semantic artifact invalid: {error}", file=sys.stderr)
        return 2
    print(f"Semantic artifact is valid: {len(nodes)} concepts, {len(edges)} relationships.")
    print("Run `kgmaker scan` to merge it into the graph.")
    return 0


def impact(root: Path, changed_files: list[str]) -> int:
    """Show files that depend on changed files via imports and call candidates."""
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1

    root = root.resolve()
    file_nodes = {node.id: node.path for node in graph.nodes if node.kind == "file"}
    node_by_id = {node.id: node for node in graph.nodes}
    path_nodes = set(file_nodes.values())
    seeds: set[str] = set()
    for raw_path in changed_files:
        candidate = Path(raw_path)
        try:
            resolved = (candidate if candidate.is_absolute() else root / candidate).resolve()
            relative = resolved.relative_to(root).as_posix()
        except (OSError, ValueError):
            print(f"Path is outside the repository: {raw_path}", file=sys.stderr)
            return 2
        if relative not in path_nodes:
            print(f"File is not in the graph: {raw_path}", file=sys.stderr)
            return 2
        seeds.add(relative)

    # Edges point from a consumer to its dependency. Reverse them to find consumers.
    dependents: dict[str, set[tuple[str, str]]] = {}
    for edge in graph.edges:
        if edge.kind == "imports":
            source_path = file_nodes.get(edge.source)
            target_path = file_nodes.get(edge.target)
            relation = "import"
        elif edge.kind == "calls":
            source_path = file_nodes.get(edge.source)
            target = node_by_id.get(edge.target)
            target_path = target.path if target else None
            relation = "candidate call"
        else:
            continue
        if source_path and target_path and source_path != target_path:
            dependents.setdefault(target_path, set()).add((source_path, relation))

    distance: dict[str, int] = {path: 0 for path in seeds}
    relations: dict[str, set[str]] = {}
    queue = sorted(seeds)
    cursor = 0
    while cursor < len(queue):
        dependency = queue[cursor]
        cursor += 1
        next_distance = distance[dependency] + 1
        for dependent, relation in sorted(dependents.get(dependency, set())):
            if dependent in seeds:
                continue
            relations.setdefault(dependent, set()).add(relation)
            if dependent not in distance:
                distance[dependent] = next_distance
                queue.append(dependent)

    print("Potential impact for: " + ", ".join(sorted(seeds)))
    impacted = sorted((path for path in distance if path not in seeds), key=lambda path: (distance[path], path))
    if not impacted:
        print("No dependent files found in the current graph.")
        return 0
    for path in impacted:
        kinds = ", ".join(sorted(relations.get(path, set())))
        confidence = "exact" if kinds == "import" else "candidate" if kinds == "candidate call" else "mixed"
        hops = distance[path]
        print(f"- {path} ({hops} hop{'s' if hops != 1 else ''}; {confidence}: {kinds})")
    print("Import links are source-resolved; call links are name-based candidates. Review source before acting.")
    return 0


def query(root: Path, terms: str, limit: int = 10) -> int:
    graph = load_graph(root)
    if graph is None:
        print("No readable graph found. Run `kgmaker scan` first.", file=sys.stderr)
        return 1
    query_terms = [part.lower() for part in terms.split() if part]
    nodes = {node.id: node for node in graph.nodes}
    scores: dict[str, int] = {}
    for node in graph.nodes:
        haystack = f"{node.name} {node.path} {node.signature or ''} {node.summary or ''}".lower()
        score = sum(4 if term == node.name.lower() else 2 if term in node.name.lower() else 1 if term in haystack else 0 for term in query_terms)
        if score:
            scores[node.id] = score
    if not scores:
        print(f"No graph entries matched: {terms}")
        return 0
    for edge in graph.edges:
        if edge.source in scores:
            scores[edge.target] = max(scores.get(edge.target, 0), scores[edge.source] - 1)
    ranked = sorted(scores.items(), key=lambda item: (-item[1], nodes[item[0]].path, nodes[item[0]].line or 0))
    print(f"Matches for {terms!r}:")
    for node_id, score in ranked[:limit]:
        node = nodes[node_id]
        location = f":{node.line}" if node.line else ""
        signature = f" — {node.signature}" if node.signature else ""
        print(f"- [{node.kind}] {node.path}{location}: {node.name}{signature} (score {score})")
    return 0


def hook_context(root: Path, token_budget: int | None = None) -> int:
    """Refresh the graph and emit sessionStart additionalContext as JSON."""
    try:
        if token_budget is not None and (isinstance(token_budget, bool) or not isinstance(token_budget, int) or token_budget < 1):
            raise ValueError("token budget must be a positive integer")
        graph, _, semantic_error = apply_semantic_layer(scan_repository(root), root)
        if semantic_error:
            print(f"kgmaker omitted stale semantic entries: {semantic_error}", file=sys.stderr)
        save_graph(graph, root)
        context_limit = max(80, token_budget * CHARS_PER_TOKEN_ESTIMATE) if token_budget else 8_000
        context = render_context(graph, limit=context_limit, root=root)
        sys.stdout.write(json.dumps({"additionalContext": context}, ensure_ascii=False) + "\n")
        return 0
    except Exception as error:  # hooks must not break a Copilot session
        print(f"kgmaker hook skipped: {error}", file=sys.stderr)
        sys.stdout.write("{}\n")
        return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="kgmaker", description="Local repository knowledge graph for GitHub Copilot CLI")
    parser.add_argument("--version", action="version", version=f"kgmaker {__version__}")
    sub = parser.add_subparsers(dest="command", required=True)

    init_parser = sub.add_parser("init", help="add Copilot hooks, instructions and the kgmaker agent")
    init_parser.add_argument("--root", type=Path, default=Path.cwd())
    init_parser.add_argument("--force", action="store_true", help="overwrite kgmaker-managed Copilot files")

    scan_parser = sub.add_parser("scan", help="scan source files and update the local graph")
    scan_parser.add_argument("--root", type=Path, default=Path.cwd())
    scan_parser.add_argument("--no-docs", action="store_true", help="skip writing GRAPH.md and GRAPH.mmd")
    scan_parser.add_argument("--confluence-dir", help="optional local Confluence HTML export directory")
    scan_parser.add_argument("--confluence-report", help="path for the generated documentation inconsistency report")

    for command in ("build", "update"):
        alias_parser = sub.add_parser(command, help=f"{command} the repository graph (full scan)")
        alias_parser.add_argument("--root", type=Path, default=Path.cwd())
        alias_parser.add_argument("--no-docs", action="store_true", help="skip writing GRAPH.md and GRAPH.mmd")
        alias_parser.add_argument("--confluence-dir", help="optional local Confluence HTML export directory")
        alias_parser.add_argument("--confluence-report", help="path for the generated documentation inconsistency report")

    status_parser = sub.add_parser("status", help="check whether the stored graph matches current source")
    status_parser.add_argument("--root", type=Path, default=Path.cwd())

    check_parser = sub.add_parser("check", help="CI check: fail if the stored graph is missing or stale")
    check_parser.add_argument("--root", type=Path, default=Path.cwd())

    docs_parser = sub.add_parser("docs", help="regenerate graph documentation and Mermaid visualization")
    docs_parser.add_argument("action", nargs="?", choices=("check", "report"), help="check/report local Confluence documentation")
    docs_parser.add_argument("--root", type=Path, default=Path.cwd())
    docs_parser.add_argument("--confluence-dir", help="local Confluence HTML export directory")
    docs_parser.add_argument("--confluence-report", help="path for the generated documentation inconsistency report")

    semantic_parser = sub.add_parser("semantic", help="prepare, incrementally update, or validate the optional agent-authored semantic layer")
    semantic_sub = semantic_parser.add_subparsers(dest="semantic_command", required=True)
    semantic_prepare_parser = semantic_sub.add_parser("prepare", help="write a stable node inventory for the Copilot extraction agent")
    semantic_prepare_parser.add_argument("--root", type=Path, default=Path.cwd())
    semantic_validate_parser = semantic_sub.add_parser("validate", help="validate .kgmaker/semantic.json against current source")
    semantic_validate_parser.add_argument("--root", type=Path, default=Path.cwd())
    semantic_update_parser = semantic_sub.add_parser("update", help="prepare a focused change packet for semantic refresh")
    semantic_update_parser.add_argument("--root", type=Path, default=Path.cwd())
    semantic_update_parser.add_argument("--base", default="HEAD~1", help="Git commit/ref to diff against (default: HEAD~1)")
    semantic_update_parser.add_argument("--note", help="optional Markdown note explaining the intent of the change")
    semantic_update_parser.add_argument("--token-budget", type=int, help="approximate maximum token budget for changed-file context")
    semantic_apply_parser = semantic_sub.add_parser("apply", help="merge the agent's scoped semantic patch")
    semantic_apply_parser.add_argument("--root", type=Path, default=Path.cwd())

    impact_parser = sub.add_parser("impact", help="show dependents of changed files")
    impact_parser.add_argument("files", nargs="+", help="changed repository-relative file paths")
    impact_parser.add_argument("--root", type=Path, default=Path.cwd())

    query_parser = sub.add_parser("query", help="find likely files and declarations")
    query_parser.add_argument("terms", nargs="+", help="words to search in graph names, paths and summaries")
    query_parser.add_argument("--root", type=Path, default=Path.cwd())
    query_parser.add_argument("--limit", type=int, default=10)

    hook_parser = sub.add_parser("hook-context", help=argparse.SUPPRESS)
    hook_parser.add_argument("--root", type=Path, default=Path.cwd())
    hook_parser.add_argument("--token-budget", type=int, help="approximate token budget for Copilot session context")
    return parser


def main() -> None:
    parser = build_parser()
    args = parser.parse_args()
    root = args.root.resolve()
    if args.command == "init":
        code = init(root, args.force)
    elif args.command in {"scan", "build", "update"}:
        code = scan(root, generate_docs=not args.no_docs, confluence_dir=args.confluence_dir, report=args.confluence_report)
    elif args.command == "status":
        code = status(root)
    elif args.command == "check":
        code = check(root)
    elif args.command == "docs":
        code = docs(root, args.action, args.confluence_dir, args.confluence_report)
    elif args.command == "semantic" and args.semantic_command == "prepare":
        code = semantic_prepare(root)
    elif args.command == "semantic" and args.semantic_command == "validate":
        code = semantic_validate(root)
    elif args.command == "semantic" and args.semantic_command == "update":
        code = semantic_update(root, args.base, args.note, args.token_budget)
    elif args.command == "semantic" and args.semantic_command == "apply":
        code = semantic_apply(root)
    elif args.command == "impact":
        code = impact(root, args.files)
    elif args.command == "query":
        code = query(root, " ".join(args.terms), args.limit)
    elif args.command == "hook-context":
        code = hook_context(root, args.token_budget)
    else:
        parser.error("unknown command")
        return
    raise SystemExit(code)


if __name__ == "__main__":
    main()
